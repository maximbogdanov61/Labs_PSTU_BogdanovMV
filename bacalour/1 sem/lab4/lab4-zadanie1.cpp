#include <iostream>
#include <cstdlib>
#include <ctime>
#include <clocale>
using namespace std;
int main(){
    setlocale(LC_ALL, ".65001"); //подключение русского языка
    srand(time(0));              //запуск датчика случайных чисел
    int M[200];                  //массив (с запасом, чтобы хватило места для добавления)
    int n;                       //реальная длина массива
    cout << "Введите длину массива (не больше 100): ";
    cin >> n;

    //1) заполняем массив случайными числами от -5 до 5
    for (int i = 0; i < n; i++)
        M[i] = rand() % 11 - 5;

    //2) печатаем массив
    cout << "Исходный массив: ";
    for (int i = 0; i < n; i++)
        cout << M[i] << " ";
    cout << endl;

    //3) удаляем все нули: ненулевые элементы переписываем в начало массива
    int k = 0;
    for (int i = 0; i < n; i++)
    {
        if (M[i] != 0)
        {
            M[k] = M[i];
            k++;
        }
    }
    n = k;                       //новая длина массива
    cout << "Массив без нулей: ";
    for (int i = 0; i < n; i++)
        cout << M[i] << " ";
    cout << endl;

    //4) ищем номер I первого чётного элемента
    int I = -1;                  //-1 значит, что чётных элементов нет
    for (int i = 0; i < n; i++)
    {
        if (M[i] % 2 == 0)
        {
            I = i;
            break;               //нашли, дальше не ищем
        }
    }

    //добавляем после него элемент M[I-1]+2
    if (I != -1)
    {
        for (int j = n; j > I + 1; j--)
            M[j] = M[j - 1];     //сдвигаем элементы вправо, чтобы освободить место
        if (I > 0)
            M[I + 1] = M[I - 1] + 2;
        else
            M[I + 1] = 2;        //если чётный элемент первый, предыдущего нет
        n++;                     //длина массива увеличилась
    }

    //5) печатаем полученный массив
    cout << "Массив после добавления элемента: ";
    for (int i = 0; i < n; i++)
        cout << M[i] << " ";
    cout << endl;
    return 0;
}